CREATE DATABASE mda CHARACTER SET utf8mb4;
use mda;
CREATE TABLE ministerio (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL
);
CREATE TABLE rol (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
nombre VARCHAR(30) NOT NULL UNIQUE
);
INSERT INTO rol (nombre) VALUES 
('ADMINISTRADOR'),
('LIDER'),
('MIEMBRO'),
('VISITANTE');
CREATE TABLE usuario (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
nombre VARCHAR (50) NOT NULL,
primer_apellido VARCHAR (60) NOT NULL,
segundo_apellido VARCHAR (60),
email VARCHAR (120) NOT NULL UNIQUE,
password VARCHAR (255) NOT NULL,
rol_id INT UNSIGNED NOT NULL,
FOREIGN KEY (rol_id) REFERENCES rol (id) 
);
CREATE TABLE pertenencia (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
usuario_id INT UNSIGNED NOT NULL,
ministerio_id INT UNSIGNED NOT NULL,
fecha_alta TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
FOREIGN KEY (ministerio_id) REFERENCES ministerio (id) ON DELETE CASCADE,
UNIQUE KEY uq_usuario_ministerio (usuario_id, ministerio_id)
);
CREATE TABLE material (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
titulo VARCHAR (60) NOT NULL,
descripcion VARCHAR (200),
ruta_archivo_url VARCHAR (250) NOT NULL,
fecha_subida TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
subido_por_id INT UNSIGNED,
FOREIGN KEY (subido_por_id) REFERENCES usuario (id) ON DELETE SET NULL
);
CREATE TABLE turno (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
fecha_hora DATETIME NOT NULL,
tarea VARCHAR (200) NOT NULL,
id_usuario INT UNSIGNED,
id_ministerio INT UNSIGNED NOT NULL,
FOREIGN KEY (id_usuario) REFERENCES usuario (id) ON DELETE SET NULL,
FOREIGN KEY (id_ministerio) REFERENCES ministerio (id) ON DELETE CASCADE
);
CREATE TABLE evento (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
titulo VARCHAR (60) NOT NULL,
descripcion VARCHAR (200),
fecha_hora DATETIME NOT NULL,
ubicacion VARCHAR (60) NOT NULL,
id_ministerio INT UNSIGNED NOT NULL,
creado_por INT UNSIGNED,
FOREIGN KEY (id_ministerio) REFERENCES ministerio (id),
FOREIGN KEY (creado_por) REFERENCES usuario (id) ON DELETE SET NULL
); 
CREATE TABLE consulta (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, 
nombre VARCHAR (100) NOT NULL,
email VARCHAR (120) NOT NULL, 
asunto VARCHAR (100) NOT NULL, 
mensaje TEXT NOT NULL,
fecha_envio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
consulta_atendida BOOLEAN DEFAULT FALSE
);
CREATE TABLE inscripcion (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, 
usuario_id INT UNSIGNED,
evento_id INT UNSIGNED NOT NULL,
nombre VARCHAR (50) NOT NULL,
primer_apellido VARCHAR (60) NOT NULL,
segundo_apellido VARCHAR (60),
email VARCHAR (120) NOT NULL,
fecha_inscripcion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
estado VARCHAR (20) DEFAULT 'CONFIRMADA',
UNIQUE KEY uq_usuario_evento (usuario_id, evento_id),
FOREIGN KEY (usuario_id) REFERENCES usuario (id),
FOREIGN KEY (evento_id) REFERENCES evento (id)
);

